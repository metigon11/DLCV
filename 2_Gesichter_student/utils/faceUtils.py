# Function to calculate the intereye distance.
def interEyeDistance(landmarks: dlib.points):
  """Calculates the intereye distance

  Parameters
  ----------
  landmarks : dlib.points
    Points generated by a 68 point face landmark detector
  """
  if len(landmarks) < 68:
    return 0

  leftEyeLeftCorner = (landmarks[36].x, landmarks[36].y)
  rightEyeRightCorner = (landmarks[45].x, landmarks[45].y)
  distance = cv2.norm(np.array(rightEyeRightCorner) - np.array(leftEyeLeftCorner))
  distance = int(distance)
  return distance


# Returns 8 points on the boundary of a rectangle
def getEightBoundaryPoints(h: float, w: float) -> npt.NDArray[np.float32]:
  """Returns 8 points on the boundary of a rectangle

  Parameters
  ----------
  h : float
    Height of the rectangle
  w : float
    Width of the rectangle

  Returns
  -------
  npt.NDArray[np.float32]
    Array containing the 8 points on the boundary of the rectangle
  """
  boundaryPts = []
  boundaryPts.append((0,0))
  boundaryPts.append((w/2, 0))
  boundaryPts.append((w-1,0))
  boundaryPts.append((w-1, h/2))
  boundaryPts.append((w-1, h-1))
  boundaryPts.append((w/2, h-1))
  boundaryPts.append((0, h-1))
  boundaryPts.append((0, h/2))
  return np.array(boundaryPts, dtype=np.float32)


# Constrains points to be inside boundary
def constrainPoint(p: Tuple[float, float], w: float, h: float) -> Tuple[float, float]:
  """Constrains points to be inside boundary

  Parameters
  ----------
  p : Tuple[float, float]
    Tuple containing the x and y coordinate
  h : float
    Height of the rectangle
  w : float
    Width of the rectangle

  Returns
  -------
  Tuple[float, float]
    Tuple containing the constrained x and y coordinate
  """
  p = (min(max(p[0], 0), w - 1), min(max(p[1], 0), h - 1))
  return p


# Check if a point is inside a rectangle
def rectContains(rect: Tuple[float, float, float, float], point: Tuple[float, float]) -> bool:
  """Checks if a point is inside a rectangle

  Parameters
  ----------
  rect : Tuple[float, float, float, float]
    Tuple containing the left, top, right, bottom coordinate of the rectangle
  point : Tuple[float, float]
    Tuple containing the x and y coordinate

  Returns
  -------
  bool
    If true than points is in rectangle
  """
  if point[0] < rect[0]:
    return False
  elif point[1] < rect[1]:
    return False
  elif point[0] > rect[2]:
    return False
  elif point[1] > rect[3]:
    return False
  return True


# Apply affine transform calculated using srcTri and dstTri to src and
# output an image of size.
def applyAffineTransform(src: MatLike, srcTri: MatLike, dstTri: MatLike, size: float) -> MatLike:
  """Apply affine transform calculated using srcTri and dstTri to src and
  output an image of size.

  Parameters
  ----------
  src : MatLike
    Source image
  srcTri : MatLike
    Coordinates of triangle vertices in the source image
  dstTri : MatLike
    Coordinates of the corresponding triangle vertices in the destination image
  size : float
    Size of the output image

  Returns
  -------
  MatLike
    Destination image with applied transform
  """
  # Given a pair of triangles, find the affine transform.
  warpMat = cv2.getAffineTransform(np.float32(srcTri), np.float32(dstTri))

  # Apply the Affine Transform just found to the src image
  dst = cv2.warpAffine(src, warpMat, (size[0], size[1]), None,
             flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)

  return dst

# Detect landmarks of face in image
def detectLandmarkPoints(im: MatLike, face: dlib.rectangle, landmarkDetector: dlib.shape_predictor, imageResizeFactor: float) -> dlib.points:
  """Uses an shape predictor to detect landmark points of an face

  Parameters
  ----------
  im : MatLike
    Image containing at least one face
  face : dlib.rectangle
    Rectangle surrounding the face
  landmarkDetector : dlib.shape_predictor
    Detector using the model 'shape_predictor_68_face_landmarks.dat'
  imageResizeFactor : float
    Factor for resizing the image

  Returns
  -------
  dlib.points
    Array containing the points of landmarks of the face
  """
  scaledFace = dlib.rectangle(
        int(face.left() / imageResizeFactor),
        int(face.top() / imageResizeFactor),
        int(face.right() / imageResizeFactor),
        int(face.bottom() / imageResizeFactor)
    )

  return landmarkDetector(im, scaledFace).parts()

def alignFace(imFace, landmarks):
  l_x = landmarks[39][0]
  l_y = landmarks[39][1]
  r_x = landmarks[42][0]
  r_y = landmarks[42][1]
  dy = r_y - l_y
  dx = r_x - l_x

  # Radian zu Deg
  angle = math.atan2(dy, dx) * 180.0 / math.pi  

  eyesCenter = ((l_x + r_x)*0.5, (l_y + r_y)*0.5)
  rotMatrix = cv2.getRotationMatrix2D(eyesCenter, angle, 1)
  alignedImFace = np.zeros(imFace.shape, dtype=np.uint8)
  alignedImFace = cv2.warpAffine(imFace, rotMatrix, 
                  (imFace.shape[1],imFace.shape[0]))

  return alignedImFace